# Writes reports/source_status.md and reports/figures/life_expectancy.png
# from the run log, the processed panel and the consistency check.

STATUS_MD <- "reports/source_status.md"
FIGURE <- "reports/figures/life_expectancy.png"

md_table <- function(df) {
  header <- paste0("| ", paste(names(df), collapse = " | "), " |")
  rule <- paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|")
  cells <- vapply(df, function(col) ifelse(is.na(col), "", as.character(col)), character(nrow(df)))
  body <- apply(matrix(cells, nrow = nrow(df)), 1, function(r) paste0("| ", paste(r, collapse = " | "), " |"))
  c(header, rule, body)
}

source_status <- function(sources, log, panel, run_at) {
  this_run <- log[log$run_at == run_at, ]
  rows <- lapply(seq_len(nrow(sources)), function(i) {
    id <- sources$source_id[i]
    updated <- log$run_at[log$source_id == id & log$status == "updated"]
    ok <- log$run_at[log$source_id == id & log$status %in% c("updated", "unchanged")]
    p <- panel[panel$source_id == id, ]
    # Every requested country is listed; one the source has no values for shows
    # as "no data", which is a coverage gap, not a failed fetch.
    latest <- paste(vapply(sort(split_countries(sources$countries[i])), function(cc) {
      y <- p$year[p$country == cc]
      if (length(y)) paste(max(y), cc) else paste("no data", cc)
    }, ""), collapse = ", ")
    data.frame(
      source_id = id,
      indicator = sources$indicator[i],
      status = this_run$status[this_run$source_id == id][1],
      last_success = if (length(ok)) substr(max(ok), 1, 10) else "never",
      last_change = if (length(updated)) substr(max(updated), 1, 10) else "never",
      latest_year = latest,
      lag_years = if (nrow(p) == 0) NA else
        as.integer(format(as.Date(run_at), "%Y")) - min(tapply(p$year, p$country, max))
    )
  })
  do.call(rbind, rows)
}

write_report <- function(sources, log, panel, consistency, run_at) {
  status <- source_status(sources, log, panel, run_at)
  problems <- log[log$run_at == run_at & log$status %in% c("failed", "schema_changed"),
                  c("source_id", "status", "message")]
  lines <- c(
    "# Source status",
    "",
    sprintf("Generated by `R/run_all.R` at %s UTC. Do not edit by hand.", run_at),
    "Source documentation: [docs/SOURCES.md](../docs/SOURCES.md).",
    "",
    "`lag_years` = year of this run minus the latest data year, for the country the source is furthest behind on.",
    "",
    md_table(status),
    "",
    "## Problems in this run",
    "",
    if (nrow(problems) == 0) "None." else md_table(problems),
    "",
    "## Cross-source consistency",
    "",
    sprintf(paste(
      "Latest year reported by both sources. Relative difference = |a - b| / mean(a, b);",
      "flagged above %d%%. A flag means the sources disagree, not that one is wrong."
    ), round(THRESHOLD * 100)),
    ""
  )
  n_sources <- tapply(panel$source_id, panel$indicator, function(x) length(unique(x)))
  single <- sort(names(n_sources)[n_sources == 1])
  if (length(single)) {
    lines <- c(lines, paste0(
      sprintf("Not compared, because only one source publishes them: %s.",
              paste0("`", single, "`", collapse = ", ")),
      if ("tb_incidence_national" %in% single) paste(
        " `tb_incidence_national` (BNS) is kept apart from WHO's modelled",
        "`tb_incidence_estimated` on purpose; see docs/SOURCES.md."
      )
    ), "")
  }
  if (is.null(consistency)) {
    lines <- c(lines, "No overlapping indicators.")
  } else {
    c2 <- consistency
    c2$value_a <- signif(c2$value_a, 4)
    c2$value_b <- signif(c2$value_b, 4)
    c2$rel_diff <- sprintf("%.1f%%", 100 * c2$rel_diff)
    c2$flagged <- ifelse(c2$flagged, "**yes**", "no")
    lines <- c(lines,
      sprintf("%d of %d comparisons flagged.", sum(consistency$flagged), nrow(consistency)),
      "", md_table(c2))
  }
  lines <- c(lines, "", "![Life expectancy by source](figures/life_expectancy.png)", "")
  dir.create(dirname(STATUS_MD), recursive = TRUE, showWarnings = FALSE)
  writeLines(lines, STATUS_MD)
  plot_life_expectancy(panel)
}

plot_life_expectancy <- function(panel) {
  le <- panel[panel$indicator == "life_expectancy", ]
  if (nrow(le) == 0) return(invisible(NULL))
  le$source <- c(gho = "WHO GHO", worldbank = "World Bank", bns = "BNS")[le$publisher]
  le <- le[le$year >= 2000, ]
  p <- ggplot2::ggplot(le, ggplot2::aes(year, value, colour = source)) +
    ggplot2::geom_line(linewidth = 0.7) +
    ggplot2::facet_wrap(~country, labeller = ggplot2::as_labeller(c(KAZ = "Kazakhstan", EGY = "Egypt"))) +
    ggplot2::scale_x_continuous(breaks = seq(2000, 2020, 10)) +
    ggplot2::scale_colour_manual(values = c("WHO GHO" = "#2a78d6", "World Bank" = "#eb6834", "BNS" = "#1baf7a")) +
    ggplot2::labs(title = "Life expectancy at birth, by source", x = NULL, y = "Years", colour = NULL,
                  caption = paste0("BNS: Bureau of National Statistics of Kazakhstan, published in months, shown in years. ",
                                    "WHO GHO: WHO Global Health Estimates.\nWorld Bank: UN World Population Prospects, national statistics offices, Eurostat.")) +
    ggplot2::theme_minimal(base_size = 11) +
    ggplot2::theme(legend.position = "top", legend.justification = "left",
                   panel.grid.minor = ggplot2::element_blank(), panel.spacing = ggplot2::unit(1.5, "lines"),
                   plot.caption = ggplot2::element_text(hjust = 0, colour = "grey35"))
  dir.create(dirname(FIGURE), recursive = TRUE, showWarnings = FALSE)
  ggplot2::ggsave(FIGURE, p, width = 8, height = 4, dpi = 150, bg = "white")
}
